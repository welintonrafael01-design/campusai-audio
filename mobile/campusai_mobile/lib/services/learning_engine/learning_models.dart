/// Deterministic recommendation generated by the Learning Engine.
class LearningRecommendation {
  final String id;
  final String title;
  final String description;
  final String type;
  final int priority;
  final String sourceId;

  const LearningRecommendation({
    required this.id,
    required this.title,
    required this.description,
    this.type = 'general',
    this.priority = 3,
    this.sourceId = '',
  });

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'description': description,
      'type': type,
      'priority': priority,
      'source_id': sourceId,
    };
  }
}

/// Lightweight badge/achievement for Student Studio.
class Achievement {
  final String id;
  final String title;
  final String description;
  final bool unlocked;
  final DateTime? unlockedAt;
  final int progress;
  final int target;

  const Achievement({
    required this.id,
    required this.title,
    required this.description,
    this.unlocked = false,
    this.unlockedAt,
    this.progress = 0,
    this.target = 1,
  });

  double get completionRatio {
    if (target <= 0) return unlocked ? 1 : 0;
    return (progress / target).clamp(0, 1);
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'description': description,
      'unlocked': unlocked,
      'unlocked_at': unlockedAt?.toIso8601String() ?? '',
      'progress': progress,
      'target': target,
    };
  }
}

/// Consecutive study-day summary.
class LearningStreak {
  final int currentStreakDays;
  final int bestStreakDays;
  final DateTime? lastStudyDate;
  final List<DateTime> studyDates;

  const LearningStreak({
    this.currentStreakDays = 0,
    this.bestStreakDays = 0,
    this.lastStudyDate,
    this.studyDates = const [],
  });

  static const empty = LearningStreak();

  Map<String, dynamic> toJson() {
    return {
      'current_streak_days': currentStreakDays,
      'best_streak_days': bestStreakDays,
      'last_study_date': lastStudyDate?.toIso8601String() ?? '',
      'study_dates': studyDates.map((date) => date.toIso8601String()).toList(),
    };
  }
}

/// Rule-based student profile summary for dashboards and coaching.
class StudentIntelligence {
  final List<String> strengths;
  final List<String> weaknesses;
  final List<String> strongCompetencies;
  final List<String> weakCompetencies;
  final String risk;
  final String level;
  final int masteryPercentage;
  final List<LearningRecommendation> recommendations;

  const StudentIntelligence({
    this.strengths = const [],
    this.weaknesses = const [],
    this.strongCompetencies = const [],
    this.weakCompetencies = const [],
    this.risk = 'Sin datos',
    this.level = 'Inicial',
    this.masteryPercentage = 0,
    this.recommendations = const [],
  });

  static const empty = StudentIntelligence();

  Map<String, dynamic> toJson() {
    return {
      'strengths': strengths,
      'weaknesses': weaknesses,
      'strong_competencies': strongCompetencies,
      'weak_competencies': weakCompetencies,
      'risk': risk,
      'level': level,
      'mastery_percentage': masteryPercentage,
      'recommendations': recommendations.map((item) => item.toJson()).toList(),
    };
  }
}
