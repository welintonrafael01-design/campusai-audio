/// Current learning item used by Student Studio to resume progress.
class ContinueLearningItem {
  final String audiobookId;
  final String audiobookTitle;
  final String chapterId;
  final String chapterTitle;
  final int progressPercentage;
  final DateTime? lastPlayedAt;

  const ContinueLearningItem({
    this.audiobookId = '',
    this.audiobookTitle = '',
    this.chapterId = '',
    this.chapterTitle = '',
    this.progressPercentage = 0,
    this.lastPlayedAt,
  });

  static const empty = ContinueLearningItem();

  bool get hasProgress => audiobookId.trim().isNotEmpty;

  Map<String, dynamic> toJson() {
    return {
      'audiobook_id': audiobookId,
      'audiobook_title': audiobookTitle,
      'chapter_id': chapterId,
      'chapter_title': chapterTitle,
      'progress_percentage': progressPercentage,
      'last_played_at': lastPlayedAt?.toIso8601String() ?? '',
    };
  }
}

